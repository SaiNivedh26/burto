"""
Burto project onboarding — zero-token approach.

Instead of burto running its own LLM scan, we write a .burto/CLAUDE.md skill
file into the project. The coding agent (cmdc / Claude Code) reads it on its
next session, uses its own model + full codebase access to analyze the project,
and writes .burto/policy.yaml directly.

Burto then loads that policy like any other policy.yaml — no extra LLM calls.
"""
from __future__ import annotations

import logging
import threading
from pathlib import Path

log = logging.getLogger("burto.analyzer")

_analyzed: set[str] = set()
_lock = threading.Lock()

_SKILL_FILENAME = "CLAUDE.md"
_POLICY_FILENAME = "policy.yaml"
_BURTO_DIR = ".burto"

# ---------------------------------------------------------------------------
# Skill template — injected into the project's .burto/CLAUDE.md
# The agent reads this and executes the analysis as part of its normal work.
# ---------------------------------------------------------------------------

_ANALYZE_SKILL = """\
# Burto: project security onboarding

**This project has no `.burto/policy.yaml`.** Before starting any task, \
analyze the codebase and generate one.

## How to analyze

Read the following (use your file tools — do not guess):

1. **Dependencies** — `requirements.txt`, `pyproject.toml`, `package.json`, `go.mod`, `Cargo.toml`
2. **Config / settings files** — any file that loads env vars (`os.environ`, `process.env`, \
`Settings`, `config.py`, `application.yml`)
3. **Service files** — look for: database clients (SQLAlchemy, psycopg2, pymongo, redis), \
payment SDKs (stripe, braintree), cloud SDKs (boto3, google-cloud, azure-storage), \
auth (JWT, OAuth, passlib), admin routes (is_superuser, /admin)
4. **Migration files** — alembic, Django migrations, Flyway
5. **Infra** — terraform/, k8s/, pulumi/, .github/workflows/

## Risk tier rules

| Tier | Conditions |
|------|-----------|
| `high` | handles payments **or** has cloud SDK + database **or** has destructive SQL + admin **or** has infra code |
| `standard` | has database or auth or migrations |
| `low` | pure tooling / scripts / library |

## Output

Write `.burto/policy.yaml` using **exactly** this schema \
(do not add extra keys — burto's parser only reads these):

```yaml
# Auto-generated by <agent> — review and commit
version: 1
risk_tier: high   # low | standard | high

model:
  active: super   # nano=low, super=standard, super=high (ultra reserved for ft)

allow:
  - tool: shell           # shell | write | read | edit | *
    command_prefix: "pytest"   # command starts with (OR use command_regex, not both)
    reason: "test runner — always safe"
  - tool: shell
    command_regex: "^git (status|diff|log|show|fetch|pull)"
    reason: "read-only git ops"
  - tool: read
    reason: "reading source files is always safe"

deny:
  - tool: write
    path_glob: "config/prod*"
    reason: "production config — only write when user explicitly asks"
  - tool: shell
    command_regex: ".*(curl|wget).*\\$(\\(|\\{).*(env|secret|password).*"
    reason: "env exfiltration pattern"

escalate:
  - tool: shell
    command_regex: ".*(terraform|kubectl|helm|pulumi).*"
    reason: "infra commands — pause and confirm with user"
  - tool: shell
    command_regex: "alembic (upgrade|downgrade)"
    reason: "db migration — confirm target revision with user"
```

**Rules:**
- Every entry needs `tool` and `reason`
- Use `command_prefix` OR `command_regex`, never both on the same rule
- `path_glob` is fnmatch syntax on the file_path
- Be specific: base rules on what you actually found in the code, not generic templates

After writing `.burto/policy.yaml`, remove this file (`.burto/CLAUDE.md`) \
so the onboarding doesn't re-run.
"""


def maybe_write_skill(project_root: str) -> bool:
    """
    If no policy exists yet, write .burto/CLAUDE.md into the project.
    The coding agent will read it and generate the policy itself.
    Returns True if the skill file was (re)written.
    """
    if not project_root:
        return False
    root = Path(project_root)
    policy_path = root / _BURTO_DIR / _POLICY_FILENAME
    skill_path = root / _BURTO_DIR / _SKILL_FILENAME

    if policy_path.exists():
        return False

    with _lock:
        if project_root in _analyzed:
            return False
        _analyzed.add(project_root)

    try:
        burto_dir = root / _BURTO_DIR
        burto_dir.mkdir(exist_ok=True)
        skill_path.write_text(_ANALYZE_SKILL, encoding="utf-8")
        log.info("wrote .burto/CLAUDE.md to %s — agent will self-analyze on next read", project_root)
        return True
    except Exception as exc:
        log.warning("failed to write skill file for %s: %s", project_root, exc)
        return False


# Keep old name as alias so hook_server /analyze endpoint still works
def maybe_analyze_async(project_root: str) -> None:
    maybe_write_skill(project_root)
